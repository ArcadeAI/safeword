function encodedClip(o: ReturnType<typeof observation>) {
  // NONRECEIPT retained fUUJyo shape: clipping is inside one JSON exec envelope.
  o.output[1].text = `Warning: truncated output (original token count: 10189)\nTotal output lines: 1\n\n${JSON.stringify(
    {
      chunk_id: 'control',
      wall_time_seconds: 1,
      exit_code: 0,
      output: o.output[1].text.slice(shape.notice.length),
    },
  )}`;
}

it('correlates complete current procedure around an encoded unrelated-guide clip', () => {
  const o = observation();
  encodedClip(o);
  expect(resourceLoad(o.turn, o.target, o.marker)).toMatchObject({
    callIds: [o.callId],
    completeBody: true,
  });
});

it.each([false, true])(
  'unsupported parallel input is candidate=%s, not a general parser extension',
  candidate => {
    const o = observation();
    // Actual SJ1Qhv destructuring/emitter shape, synthetic output; NOT a receipt.
    o.turn.entries.unshift(
      {
        type: 'response_item',
        payload: {
          type: 'custom_tool_call',
          call_id: 'unsupported',
          input: `const [a,b] = await Promise.all([tools.exec_command({"cmd":"node --test"}),tools.exec_command({"cmd":"node probe.js"})]); text(JSON.stringify({tests:a,probe:b}));`,
        },
      },
      {
        type: 'response_item',
        payload: {
          type: 'custom_tool_call_output',
          call_id: 'unsupported',
          output: candidate
            ? o.body
            : JSON.stringify({ tests: { output: 'unrelated tests' }, probe: { output: 'probe' } }),
        },
      },
    );
    if (candidate)
      expect(() => resourceLoad(o.turn, o.target, o.marker)).toThrow(
        'HOST_CONTRACT_PROOF_UNAVAILABLE',
      );
    else expect(resourceLoad(o.turn, o.target, o.marker).callIds).toEqual([o.callId]);
  },
);

type Observation = ReturnType<typeof observation>;
const mutations: Record<string, (o: Observation) => void> = {
  'clipped-body': o => {
    o.output[1].text = o.output[1].text.replace(o.body, () => o.body.slice(0, -100));
  },
  'sdk-clipped-body': o => {
    o.event.item.aggregated_output = o.event.item.aggregated_output.replace(o.body, () =>
      o.body.slice(0, -100),
    );
  },
  'failed-sdk': o => {
    o.event.item.exit_code = 1;
  },
  'wrong-sdk-command': o => {
    o.event.item.command = '/bin/zsh -lc "echo unrelated"';
  },
  'wrong-call': o => {
    const entry = o.entries.at(1);
    if (!entry) throw new Error('missing unit output');
    entry.payload.call_id = 'foreign';
  },
  'stale-body': o => {
    const stale = o.body.replace('Testing', 'Stale testing');
    o.output[1].text = o.output[1].text.replace(o.body, () => stale);
    o.event.item.aggregated_output = o.event.item.aggregated_output.replace(o.body, () => stale);
  },
  'foreign-output': o => {
    o.event.item.aggregated_output = `foreign head\n${o.event.item.aggregated_output}`;
  },
  'unknown-banner': o => {
    o.output[1].text = `Other transport notice\n${o.output[1].text}`;
  },
  'malformed-banner': o => {
    o.output[1].text = o.output[1].text.replace('404', 'unknown');
  },
  encoded: o => {
    o.output[1].text =
      shape.notice + JSON.stringify({ chunk_id: 'unit', exit_code: 0, output: o.body });
  },
  'double-encoded': o => {
    o.output[1].text = shape.notice + JSON.stringify(JSON.stringify({ output: o.body }));
  },
  'repeated-notice': o => {
    o.output[1].text = shape.notice + o.output[1].text;
  },
  'multiple-omissions': o => {
    o.output[1].text += shape.omission;
  },
  'no-omitted-middle': o => {
    o.event.item.aggregated_output = o.head + o.tail;
  },
  'sdk-only-repeats-clipped-view': o => {
    o.event.item.aggregated_output = o.head + shape.omission + o.tail;
  },
  'sdk-not-completed': o => {
    o.event.type = 'item.started';
  },
  'malformed-omission': o => {
    o.output[1].text = o.output[1].text.replace(
      '…908 tokens truncated…',
      '...908 tokens truncated...',
    );
  },
};

it.each(Object.entries(mutations))(
  'rejects independent %s plain truncation evidence',
  (_kind, mutate) => {
    const o = observation();
    mutate(o);
    expect(() => resourceLoad(o.turn, o.target, o.marker)).toThrow();
  },
);

it.each([
  'clipped-body',
  'sdk-clipped-body',
  'failed-sdk',
  'wrong-call',
  'stale-body',
  'foreign-output',
  'multiple-omissions',
  'no-omitted-middle',
  'sdk-only-repeats-clipped-view',
  'malformed-omission',
])('rejects encoded clip %s', fault => {
  const o = observation();
  mutations[fault]?.(o);
  encodedClip(o);
  expect(() => resourceLoad(o.turn, o.target, o.marker)).toThrow();
});

it('does not credit a prior-turn observation', () => {
  const o = observation();
  expect(() => resourceLoad({ ...o.turn, afterEntryIndex: 1 }, o.target, o.marker)).toThrow();
});
