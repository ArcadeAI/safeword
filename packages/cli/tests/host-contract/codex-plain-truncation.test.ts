import { copyFileSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { afterEach, expect, it } from 'vitest';

import callback from '../fixtures/host-contract/codex-agent-message.json' with { type: 'json' };
import shape from '../fixtures/host-contract/codex-plain-truncation-shape.json' with { type: 'json' };
import { type NativeTurn, resourceLoad } from '../helpers/codex-workflow-observation.js';

const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

// Caller-level NONRECEIPT controls: current generated bytes, mocked host transcript only.
function observation() {
  const root = mkdtempSync(path.join(tmpdir(), 'safeword-plain-truncation-'));
  roots.push(root);
  const target = path.join(root, 'SKILL.md');
  copyFileSync(
    path.join(import.meta.dirname, '../../codex-plugin/internal/testing/SKILL.md'),
    target,
  );
  const body = readFileSync(target, 'utf8');
  const marker = 'SAFEWORD:TESTING_CORE_START';
  const head = 'Unrelated catalogue output\n';
  const tail = `\n${body}\nUnrelated project output\n`;
  const omitted = 'Unrelated omitted catalogue entries\n';
  const command = `rg --files ${root}; sed -n '1,260p' ${target}; cat package.json`;
  const callId = 'call_8279fcb93d344ae8913e81ef99818fda';
  const output = [
    { type: 'input_text', text: shape.preamble },
    { type: 'input_text', text: shape.notice + head + shape.omission + tail },
  ] as [{ type: string; text: string }, { type: string; text: string }];
  const event = {
    type: 'item.completed',
    item: {
      type: 'command_execution',
      command: `/bin/zsh -lc ${JSON.stringify(command)}`,
      exit_code: 0,
      aggregated_output: head + omitted + tail,
    },
  };
  const entries = [
    {
      type: 'response_item',
      payload: {
        type: 'custom_tool_call',
        name: 'exec',
        call_id: callId,
        input: `const r = await tools.exec_command(${JSON.stringify({ cmd: command })});\ntext(r.output);\n`,
      },
    },
    {
      type: 'response_item',
      payload: { type: 'custom_tool_call_output', call_id: callId, output },
    },
  ];
  const turn = { entries, events: [event] } as Pick<NativeTurn, 'entries' | 'events'>;
  return { target, marker, body, head, tail, output, event, entries, turn, callId };
}

it('recognizes complete current body in captured plain truncation with successful SDK correspondence', () => {
  const o = observation();
  expect(resourceLoad(o.turn, o.target, o.marker)).toMatchObject({
    callIds: [o.callId],
    completeBody: true,
  });
});

it('retains actual current body proof beside the captured informational callback', () => {
  const o = observation();
  o.turn.entries.unshift(structuredClone(callback.entry));
  expect(resourceLoad(o.turn, o.target, o.marker).callIds).toEqual([o.callId]);
});

it('does not use callback text as native Skill context or tool evidence', () => {
  const o = observation();
  const message = structuredClone(callback.entry);
  message.payload.content = [
    { type: 'input_text', text: `<skill><path>${o.target}</path>${o.body}</skill>` },
  ];
  o.turn.entries = [message];
  expect(() => resourceLoad(o.turn, o.target, o.marker, true)).toThrow();
});

