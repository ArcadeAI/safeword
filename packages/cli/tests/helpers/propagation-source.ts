import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { cpSync, mkdirSync, readFileSync, renameSync, symlinkSync, writeFileSync } from 'node:fs';
import nodePath from 'node:path';

import { VERSION } from '../../src/version.js';
import { command } from './cursor-native-window.js';
import { createCursorProjectSource } from './cursor-project-catalogue.js';
import type { CanonicalCatalogueInputs } from './native-catalogue-probe.js';

const cliRoot = nodePath.resolve(import.meta.dirname, '../..');
const repoRoot = nodePath.resolve(cliRoot, '../..');
export const propagationVerificationOwner = 'hooks/lib/done-gate.ts';
/** Concrete controllers supply installed roots; no Markdown or opaque identity parsing. */
export function installedPropagationPaths(
  root: string,
  layout: 'portable' | 'claude' | 'project',
  policyRoot = root,
) {
  const hooks = { portable: 'templates/hooks', claude: 'runtime/hooks', project: 'hooks' }[layout];
  const skill = nodePath.join(root, 'skills/explain');
  return {
    resources: [
      nodePath.join(skill, 'SKILL.md'),
      nodePath.join(
        skill,
        layout === 'portable' ? 'references/HOST_CONTRACT_GUIDE.md' : 'HOST_CONTRACT_GUIDE.md',
      ),
      nodePath.join(root, hooks, 'audit-principle-trace.ts'),
    ],
    policy: nodePath.join(policyRoot, hooks, 'lib/done-gate.ts'),
  };
}

export function propagationFingerprint(paths: ReturnType<typeof installedPropagationPaths>) {
  const sha = (file: string) => createHash('sha256').update(readFileSync(file)).digest('hex');
  return { resources: paths.resources.map(sha), policy: sha(paths.policy) };
}
const signature = 'export function checkVerifyArtifact(content: string): VerifyArtifactStatus {';

/** Change exactly the existing owner in an owned canonical fixture, not a host adapter. */
export function requirePropagationVerificationMarker(
  inputs: CanonicalCatalogueInputs,
  marker: string,
): void {
  assert.match(marker, /^VERIFICATION_[a-f0-9-]+$/u);
  const file = nodePath.join(inputs.canonicalRoot, propagationVerificationOwner);
  const content = readFileSync(file, 'utf8');
  assert.equal(content.split(signature).length, 2, 'PROPAGATION_POLICY_OWNER_CHANGED');
  const reason = JSON.stringify(`PROPAGATION_VERIFICATION_MARKER_REQUIRED:${marker}`);
  writeFileSync(
    file,
    content.replace(
      signature,
      () =>
        `${signature}\n  if (!content.includes(${JSON.stringify(marker)})) return { ok: false, reason: ${reason} };`,
    ),
  );
}

/** Existing generators resolve packageRoot from their own source location. */
export function createPropagationSource(
  directory: string,
  inputs: CanonicalCatalogueInputs,
  skill = 'explain',
) {
  const repo = nodePath.join(directory, 'source');
  const packages = nodePath.join(repo, 'packages');
  mkdirSync(packages, { recursive: true });
  const prepared = createCursorProjectSource(packages, inputs, skill);
  const source = nodePath.join(packages, 'cli');
  // SDK source imports the existing sibling CLI package by its real layout.
  renameSync(prepared, source);
  for (const name of ['scripts', 'codex-plugin'])
    cpSync(nodePath.join(cliRoot, name), nodePath.join(source, name), { recursive: true });
  cpSync(nodePath.join(repoRoot, 'package.json'), nodePath.join(repo, 'package.json'));
  cpSync(nodePath.join(repoRoot, '.prettierrc'), nodePath.join(repo, '.prettierrc'));
  const sdk = nodePath.join(packages, 'opencode-v2-plugin');
  mkdirSync(sdk);
  for (const name of ['src', 'package.json'])
    cpSync(nodePath.join(repoRoot, 'packages/opencode-v2-plugin', name), nodePath.join(sdk, name), {
      recursive: true,
    });
  symlinkSync(nodePath.join(repoRoot, 'node_modules'), nodePath.join(repo, 'node_modules'));
  return source;
}

/** One canonical revision for installed templates and bundled runtime alike. */
export function synchronizePropagationSource(inputs: CanonicalCatalogueInputs): string {
  const source = inputs.sourcePackage;
  assert.ok(source, 'PROPAGATION_OWNED_SOURCE_REQUIRED');
  // One shared preparation before every normal bundler: resources and runtime
  // must consume the same canonical revision, including subsequent mutations.
  cpSync(inputs.canonicalRoot, nodePath.join(source, 'templates'), { recursive: true });
  return source;
}

/** Normal generator, including normal runtime bundling; no generated byte patching. */
export async function generatePropagationPackage(
  inputs: CanonicalCatalogueInputs,
  output: string,
  host: 'portable' | 'codex' | 'opencode' | 'claude' | 'cursor',
): Promise<void> {
  const source = synchronizePropagationSource(inputs);
  const home = nodePath.join(nodePath.dirname(output), '.generation-home');
  const environment = {
    ...process.env,
    HOME: home,
    XDG_CONFIG_HOME: nodePath.join(home, 'config'),
    CODEX_HOME: nodePath.join(home, 'codex'),
    CLAUDE_CONFIG_DIR: nodePath.join(home, 'claude'),
    OPENCODE_CONFIG_DIR: nodePath.join(home, 'opencode'),
  };
  if (host === 'claude') {
    // Preserve Claude's normal final planning-copy identities and catalogue seal.
    mkdirSync(output, { recursive: true });
    await command('bun', [nodePath.join(source, 'scripts/generate-claude-plugin.ts')], {
      cwd: source,
      env: { ...environment, SAFEWORD_CLAUDE_GENERATED_PLUGIN_ROOT: output },
      timeout: 120_000,
    });
    return;
  }
  const script = {
    portable: 'generate-codex-plugin.ts',
    codex: 'generate-codex-plugin.ts',
    opencode: 'generate-opencode-v2-plugin.ts',
    cursor: 'generate-cursor-plugin.ts',
  }[host];
  await command(
    'bun',
    [
      nodePath.join(source, 'scripts', script),
      ...(host === 'portable' ? ['--portable-core'] : []),
      ...(host === 'portable' || host === 'codex' ? ['--version', VERSION] : []),
      '--output',
      output,
    ],
    { cwd: source, env: environment, timeout: 120_000 },
  );
}
