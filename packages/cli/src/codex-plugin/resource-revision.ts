import { createHash } from 'node:crypto';
import { lstatSync, readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import nodePath from 'node:path';

import { CODEX_WORKFLOW_LAYOUT } from '../schema-layouts.js';

function resourceFiles(root: string, relative: string): [string, string][] {
  const file = nodePath.join(root, ...relative.split('/'));
  // File-only packaging omits empty optional roots. Nested and required paths
  // still throw normally; lstat also exposes dangling links for rejection.
  const optionalRoot =
    relative === CODEX_WORKFLOW_LAYOUT.skills || relative === CODEX_WORKFLOW_LAYOUT.internal;
  const stat = lstatSync(file, { throwIfNoEntry: !optionalRoot });
  if (!stat) return [];
  if (stat.isSymbolicLink()) throw new Error(`Resource symlink: ${relative}`);
  if (stat.isDirectory())
    return readdirSync(file).flatMap(name => resourceFiles(root, `${relative}/${name}`));
  if (!stat.isFile()) throw new Error(`Invalid resource: ${relative}`);
  return [[relative, createHash('sha256').update(readFileSync(file)).digest('hex')]];
}

/** Complete owned resource superset; compiler/runtime and index self-content excluded. */
export function nativeResourceRevision(packageRoot: string): string {
  const root = realpathSync(packageRoot);
  const { skills, internal, templates, handbook } = CODEX_WORKFLOW_LAYOUT;
  const entries = [skills, internal, templates, handbook]
    .flatMap(relative => resourceFiles(root, relative))
    .toSorted(([left], [right]) => (left < right ? -1 : 1));
  return createHash('sha256').update(JSON.stringify(entries)).digest('hex');
}

export function validatedResourceRevision(root: string, index: unknown): string {
  const revision = (index as { resourceRevision?: { version?: unknown; sha256?: unknown } })
    ?.resourceRevision;
  if (
    revision?.version !== 1 ||
    typeof revision.sha256 !== 'string' ||
    !/^[a-f\d]{64}$/u.test(revision.sha256)
  )
    throw new Error('Invalid or missing resource revision');
  if (revision.sha256 !== nativeResourceRevision(root)) throw new Error('Stale resource revision');
  return revision.sha256;
}

/** Called only after every resource carrier has its final generated bytes. */
export function finalizeWorkflowRevision(root: string): string {
  const file = nodePath.join(root, CODEX_WORKFLOW_LAYOUT.index);
  const index = JSON.parse(readFileSync(file, 'utf8')) as Record<string, unknown>;
  const sha256 = nativeResourceRevision(root);
  index.resourceRevision = { version: 1, sha256 };
  writeFileSync(file, `${JSON.stringify(index, undefined, 2)}\n`);
  return sha256;
}

export function resourceRevisionContext(revision: string): string {
  return `Resource revision: ${revision}\nUse applicable CURRENT installed resources in this process; earlier thread content may be stale. Optional references stay optional.`;
}
